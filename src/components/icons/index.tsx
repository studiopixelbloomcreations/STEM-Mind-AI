// Helper component for creating consistent custom icons
const createIcon = (name: string, renderPaths: (props: IconProps) => React.ReactNode) => {
  const Component: React.FC<IconProps> = ({
    size = 20,
    strokeWidth = 1.75,
    color = 'currentColor',
    className = '',
    ...props
  }) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      {...props}
    >
      {renderPaths({ size, strokeWidth, color, className, ...props })}
    </svg>
  );
  Component.displayName = name;
  return Component;
};

